"""
Report Generator for IntelliDecision AI
Generates downloadable Markdown reports and styled PDF decision summary documents using fpdf2.
"""

from fpdf import FPDF
import json
import datetime

class DecisionPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(99, 102, 241) # Primary indigo
        self.cell(0, 10, "IntelliDecision AI - Decision Intelligence Report", border=0, new_x="LMARGIN", new_y="NEXT", align="R")
        self.set_draw_color(200, 200, 200)
        self.line(10, 18, 200, 18)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 9)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by IntelliDecision AI Platform", border=0, align="C")

def generate_markdown_report(title: str, category: str, report_data: dict, tradeoffs: dict, hidden_factors: dict) -> str:
    """Generate clean Markdown string representation of the decision report."""
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    
    rec = report_data.get("final_recommendation", {})
    recommended_option = rec.get("recommended_option", "N/A")
    confidence = rec.get("confidence_score", 85)
    justification = rec.get("primary_justification", "")
    
    md = f"""# 🧠 IntelliDecision AI - Decision Intelligence Report

**Decision Title:** {title}  
**Category:** {category}  
**Generated On:** {now}  
**AI Confidence Score:** `{confidence}%`  

---

## 🏆 Final Recommendation
**Winning Option:** **{recommended_option}**

### Key Justification:
{justification}

---

## 📊 Executive Summary
{report_data.get('executive_summary', '')}

---

## 🔍 Hidden Factors & Blindspots Analysis
- **Hidden Costs:** {", ".join(hidden_factors.get('hidden_costs', []))}
- **Second-Order Effects:** {", ".join(hidden_factors.get('second_order_effects', []))}
- **Cognitive Biases Identified:** {", ".join([b.get('bias', '') for b in hidden_factors.get('cognitive_biases_to_watch', [])])}

---

## ⚖️ Trade-Off Verdict
{tradeoffs.get('tradeoff_verdict', '')}

---

## 🚀 Recommended Action Plan
"""
    action_plan = report_data.get("action_plan", [])
    for phase_info in action_plan:
        phase = phase_info.get("phase", "Phase")
        steps = phase_info.get("steps", [])
        md += f"\n### {phase}\n"
        for s in steps:
            md += f"- [ ] {s}\n"

    md += f"\n---\n\n## 🛡️ Contingency & Plan B\n{report_data.get('contingency_plan', '')}\n"
    return md

def generate_pdf_report(title: str, category: str, report_data: dict, tradeoffs: dict) -> bytes:
    """Generate PDF binary bytes for download."""
    pdf = DecisionPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    # Title
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(30, 41, 59)
    pdf.multi_cell(0, 10, title)
    pdf.ln(3)
    
    # Category & Metadata
    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, f"Category: {category} | Generated by IntelliDecision AI Engine", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)
    
    # Recommendation Box
    rec = report_data.get("final_recommendation", {})
    recommended_option = rec.get("recommended_option", "N/A")
    confidence = rec.get("confidence_score", 85)
    
    pdf.set_fill_color(240, 242, 254) # Soft indigo tint
    pdf.set_draw_color(99, 102, 241)
    pdf.rect(10, pdf.get_y(), 190, 28, style="FD")
    
    pdf.set_xy(14, pdf.get_y() + 4)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(99, 102, 241)
    pdf.cell(0, 6, f"RECOMMENDED OPTION: {recommended_option} (Confidence: {confidence}%)", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_x(14)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(51, 65, 85)
    justification = rec.get("primary_justification", "")
    pdf.multi_cell(182, 5, justification[:200])
    pdf.ln(12)
    
    # Executive Summary
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(0, 8, "Executive Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(71, 85, 105)
    pdf.multi_cell(0, 5, report_data.get("executive_summary", ""))
    pdf.ln(8)
    
    # Action Plan
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(0, 8, "Implementation Action Plan", new_x="LMARGIN", new_y="NEXT")
    
    action_plan = report_data.get("action_plan", [])
    for phase_info in action_plan:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(99, 102, 241)
        pdf.cell(0, 6, phase_info.get("phase", "Phase"), new_x="LMARGIN", new_y="NEXT")
        
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(51, 65, 85)
        for s in phase_info.get("steps", []):
            pdf.cell(10, 5, "-")
            pdf.multi_cell(0, 5, s)
        pdf.ln(2)

    return bytes(pdf.output())
