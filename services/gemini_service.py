"""
Gemini Service Module for IntelliDecision AI
Provides integration with Google's Gemini API using the official google-genai SDK.
Handles model execution, configuration, error recovery, and model fallbacks.
"""

import os
import logging
from typing import Optional, List
from dotenv import load_dotenv
from google import genai
from google.genai import types

# Load environment variables from .env file
load_dotenv()

# Logger configuration
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("IntelliDecision.GeminiService")

# Service Constants
DEFAULT_MODEL: str = "gemini-2.5-flash"
FALLBACK_MODELS: List[str] = ["gemini-2.0-flash", "gemini-1.5-flash"]


class GeminiService:
    """
    Reusable production-grade service for interacting with Google's Gemini API models.
    Provides automatic retry with fallback models and structured output configurations.
    """

    def __init__(self, model_name: str = DEFAULT_MODEL) -> None:
        """
        Initialize the Gemini Client with the API key from environment variables.

        :param model_name: Primary Gemini model to use (default: gemini-2.5-flash).
        :raises ValueError: If GEMINI_API_KEY environment variable is not configured.
        :raises RuntimeError: If initializing the google-genai Client fails.
        """
        self.api_key: Optional[str] = os.getenv("GEMINI_API_KEY")
        if not self.api_key:
            logger.warning("GEMINI_API_KEY is missing from environment variables.")
            self.client: Optional[genai.Client] = None
            self.model_name: str = model_name
            return

        self.model_name: str = model_name
        try:
            self.client = genai.Client(api_key=self.api_key)
            logger.info(f"GeminiService initialized successfully with primary model '{self.model_name}'.")
        except Exception as e:
            logger.error(f"Failed to initialize Gemini client: {e}", exc_info=True)
            self.client = None

    def is_configured(self) -> bool:
        """
        Checks whether the Gemini client is active and API key is loaded.

        :return: True if client is ready for calls, False otherwise.
        """
        return bool(self.api_key and self.client)

    def generate_content(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        response_mime_type: Optional[str] = None
    ) -> str:
        """
        Unified method to query Gemini models with automatic fallback across models.

        :param prompt: Main text prompt to submit to the model.
        :param system_instruction: Optional system instruction guiding model behavior.
        :param response_mime_type: Optional MIME type (e.g. 'application/json') for output format.
        :return: String output generated by Gemini model.
        :raises RuntimeError: If client is not initialized or all model attempts fail.
        """
        if not self.is_configured():
            raise RuntimeError("GEMINI_API_KEY environment variable is missing or invalid.")

        config = types.GenerateContentConfig()
        if system_instruction:
            config.system_instruction = system_instruction
        if response_mime_type:
            config.response_mime_type = response_mime_type

        candidate_models: List[str] = [self.model_name] + [m for m in FALLBACK_MODELS if m != self.model_name]

        last_exception: Optional[Exception] = None
        for model in candidate_models:
            try:
                response = self.client.models.generate_content(
                    model=model,
                    contents=prompt,
                    config=config
                )
                if response and response.text:
                    return response.text
            except Exception as exc:
                logger.warning(f"Model '{model}' call failed: {exc}. Trying next candidate...")
                last_exception = exc

        raise RuntimeError(f"All Gemini model invocations failed. Last error: {last_exception}")

    def analyze_decision(self, decision_text: str) -> str:
        """
        Analyzes the initial decision text provided by the user.

        :param decision_text: Text description of the decision problem.
        :return: Plain text string containing the AI analysis.
        """
        if not decision_text or not decision_text.strip():
            return "Error: Decision text cannot be empty."

        system_instruction = (
            "You are an executive Decision Intelligence Advisor. "
            "Analyze the decision scenario: identify core problem statement, key strategic objectives, "
            "primary uncertainties, and initial executive insights."
        )
        prompt = f"Decision Scenario:\n{decision_text.strip()}"

        try:
            return self.generate_content(prompt, system_instruction=system_instruction)
        except Exception as e:
            logger.error(f"Error in analyze_decision: {e}")
            return f"Error analyzing decision: {str(e)}"

    def generate_followup_questions(self, decision_text: str) -> str:
        """
        Generates probing follow-up questions to help uncover hidden context and constraints.

        :param decision_text: Text description or context of the decision.
        :return: Plain text string containing generated follow-up questions.
        """
        if not decision_text or not decision_text.strip():
            return "Error: Decision text cannot be empty."

        system_instruction = (
            "You are a Decision Analyst. Based on the decision scenario, generate 4 probing "
            "follow-up questions forcing clarification on priorities, resource limits, timelines, and risk tolerance."
        )
        prompt = f"Decision Scenario:\n{decision_text.strip()}"

        try:
            return self.generate_content(prompt, system_instruction=system_instruction)
        except Exception as e:
            logger.error(f"Error in generate_followup_questions: {e}")
            return f"Error generating follow-up questions: {str(e)}"

    def generate_final_report(self, context: str) -> str:
        """
        Generates a comprehensive final decision report summarizing analysis, trade-offs, and recommendations.

        :param context: Consolidated context string containing decision details, Q&A responses, and evaluations.
        :return: Plain text executive decision report.
        """
        if not context or not context.strip():
            return "Error: Decision context cannot be empty."

        system_instruction = (
            "You are a C-suite Strategy Advisor. Synthesize the decision context into a "
            "comprehensive Executive Decision Report including executive summary, recommended action, "
            "trade-off analysis, action plan, and contingency plan."
        )
        prompt = f"Decision Context:\n{context.strip()}"

        try:
            return self.generate_content(prompt, system_instruction=system_instruction)
        except Exception as e:
            logger.error(f"Error in generate_final_report: {e}")
            return f"Error generating final report: {str(e)}"
