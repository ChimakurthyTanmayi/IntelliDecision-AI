"""
Report Generator Module for IntelliDecision AI
Formats structured decision analysis data into Executive Decision Reports.
Generates downloadable Markdown reports, JSON data exports, and styled PDF summary documents using fpdf2.
"""

import json
import logging
import datetime
from typing import Dict, Any, List
from fpdf import FPDF

logger = logging.getLogger("IntelliDecision.ReportGenerator")


class DecisionPDF(FPDF):
    """
    Custom FPDF class for styling Executive Decision Intelligence PDF reports.
    """

    def header(self) -> None:
        """Render standard PDF document header banner."""
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(99, 102, 241)  # Primary indigo accent
        self.cell(0, 8, "IntelliDecision AI — Executive Decision Report", border=0, new_x="LMARGIN", new_y="NEXT", align="R")
        self.set_draw_color(226, 232, 240)
        self.line(10, 16, 200, 16)
        self.ln(4)

    def footer(self) -> None:
        """Render standard PDF document footer with page numbering."""
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by IntelliDecision AI Platform", border=0, align="C")


class ReportGenerator:
    """
    Synthesizes and formats multi-agent decision analysis outputs into structured,
    human-readable Executive Decision Reports ready for UI display or download as Markdown, PDF, and JSON.
    """

    def generate_report(self, analysis_result: Dict[str, Any], decision_title: str = "") -> Dict[str, Any]:
        """
        Transforms raw decision analysis data into a comprehensive report dictionary.

        :param analysis_result: Output dictionary from DecisionAnalyzer.analyze()
        :param decision_title: Optional title/headline of the decision.
        :return: Formatted report dictionary matching expected UI schema.
        """
        if not analysis_result or not isinstance(analysis_result, dict):
            logger.warning("Invalid or empty analysis_result passed to ReportGenerator.")
            return self._get_default_report("Executive Decision Intelligence Report")

        summary: str = str(analysis_result.get("decision_summary", "Decision analysis complete.")).strip()
        rec_option: str = str(analysis_result.get("recommended_option", analysis_result.get("recommendation", "Proceed with primary option"))).strip()
        reasoning: str = str(analysis_result.get("reasoning", "")).strip()
        confidence_score: int = self._sanitize_score(analysis_result.get("confidence_score", 85))

        title: str = decision_title.strip() if decision_title and decision_title.strip() else "Executive Decision Intelligence Report"

        exec_summary: str = f"{summary} Based on multi-agent evaluation, risk trade-offs, and multi-criteria scoring, the recommended path forward is {rec_option} (Confidence Score: {confidence_score}%)."

        why_wins: List[str] = self._sanitize_list(analysis_result.get("why_recommended_wins"))
        why_weaker: List[str] = self._sanitize_list(analysis_result.get("why_others_are_weaker"))
        hidden_assumptions: List[str] = self._sanitize_list(analysis_result.get("hidden_assumptions"))
        cognitive_biases: List[str] = self._sanitize_list(analysis_result.get("cognitive_biases"))
        action_plan: List[str] = self._sanitize_list(analysis_result.get("action_plan_30_60_90"))
        contingency_triggers: List[str] = self._sanitize_list(analysis_result.get("contingency_triggers"))

        pros: List[str] = self._sanitize_list(analysis_result.get("pros"))
        cons: List[str] = self._sanitize_list(analysis_result.get("cons"))
        trade_offs: List[str] = self._sanitize_list(analysis_result.get("trade_offs"))
        risks: List[str] = self._sanitize_list(analysis_result.get("risks"))
        opportunities: List[str] = self._sanitize_list(analysis_result.get("opportunities"))

        risk_analysis = analysis_result.get("risk_analysis", {})
        decision_matrix = analysis_result.get("decision_matrix", {})
        swot_analysis = analysis_result.get("swot_analysis", {})

        return {
            "title": title,
            "executive_summary": exec_summary,
            "decision_overview": summary,
            "recommended_option": rec_option,
            "final_recommendation": f"Recommended Path: {rec_option}\n\nStrategic Rationale:\n{reasoning if reasoning else exec_summary}",
            "confidence_score": confidence_score,
            "why_recommended_wins": why_wins,
            "why_others_are_weaker": why_weaker,
            "hidden_assumptions": hidden_assumptions,
            "cognitive_biases": cognitive_biases,
            "action_plan_30_60_90": action_plan,
            "contingency_triggers": contingency_triggers,
            "pros": pros,
            "cons": cons,
            "trade_offs": trade_offs,
            "risk_assessment": risks,
            "opportunities": opportunities,
            "risk_analysis": risk_analysis,
            "decision_matrix": decision_matrix,
            "swot_analysis": swot_analysis,
            "key_takeaways": why_wins[:3] if why_wins else [f"Primary Action: {rec_option}"],
            "next_steps": action_plan
        }

    def generate_markdown(self, report: Dict[str, Any]) -> str:
        """Generates clean Markdown string from report dictionary for download."""
        now: str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        title: str = report.get("title", "Executive Decision Intelligence Report")
        confidence: int = report.get("confidence_score", 85)
        rec_opt: str = report.get("recommended_option", "Primary Option")

        md = f"""# 🧠 IntelliDecision AI — Executive Decision Intelligence Report

**Decision Title:** {title}  
**Generated On:** {now}  
**Winning Recommendation:** `{rec_opt}`  
**Confidence Score:** `{confidence}%`  

---

## 📌 Executive Summary
{report.get('executive_summary', '')}

---

## 🏆 Recommended Path & Strategic Rationale
**Winning Option:** **{rec_opt}**

### Why This Option Wins:
"""
        for w in report.get("why_recommended_wins", []):
            md += f"- ✅ {w}\n"

        md += "\n### Why Alternative Choices Are Weaker:\n"
        for w in report.get("why_others_are_weaker", []):
            md += f"- ⚠️ {w}\n"

        md += "\n---\n\n## 🧠 Cognitive Biases & Hidden Assumptions\n"
        md += "### Unexamined Hidden Assumptions:\n"
        for ha in report.get("hidden_assumptions", []):
            md += f"- 🔍 {ha}\n"

        md += "\n### Potential Cognitive Biases at Play:\n"
        for cb in report.get("cognitive_biases", []):
            md += f"- 🧩 {cb}\n"

        md += "\n---\n\n## 📅 30-60-90 Day Action Plan & Contingency\n"
        for ap in report.get("action_plan_30_60_90", []):
            md += f"- [ ] {ap}\n"

        md += "\n### Downside Contingency Triggers:\n"
        for ct in report.get("contingency_triggers", []):
            md += f"- 🚨 {ct}\n"

        return md

    def generate_json(self, report: Dict[str, Any]) -> str:
        """Generates formatted JSON export string."""
        return json.dumps(report, indent=2)

    def generate_pdf(self, report: Dict[str, Any]) -> bytes:
        """Generates styled PDF document binary bytes from a report dictionary."""
        pdf = DecisionPDF()
        pdf.add_page()
        pdf.set_auto_page_break(auto=True, margin=15)

        title: str = report.get("title", "Executive Decision Intelligence Report")
        confidence: int = report.get("confidence_score", 85)
        rec_opt: str = report.get("recommended_option", "Primary Option")

        # Title
        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(15, 23, 42)
        pdf.multi_cell(0, 8, title)
        pdf.ln(2)

        # Metadata
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(0, 6, f"Confidence Score: {confidence}% | Powered by Gemini 2.5 Multi-Agent Platform", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

        # Recommendation Box
        pdf.set_fill_color(240, 242, 254)
        pdf.set_draw_color(99, 102, 241)
        pdf.rect(10, pdf.get_y(), 190, 24, style="FD")

        pdf.set_xy(14, pdf.get_y() + 3)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(79, 70, 229)
        pdf.cell(0, 5, f"WINNING RECOMMENDATION: {rec_opt.upper()}", new_x="LMARGIN", new_y="NEXT")

        pdf.set_x(14)
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(30, 41, 59)
        rec_text: str = report.get("executive_summary", "")[:250]
        pdf.multi_cell(182, 4, rec_text)
        pdf.ln(10)

        # Why Recommended Wins
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "Why This Option Wins", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        for win in report.get("why_recommended_wins", []):
            pdf.cell(6, 4, "•")
            pdf.multi_cell(0, 4, win)
        pdf.ln(4)

        # Why Others Are Weaker
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "Why Alternatives Are Weaker", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        for weak in report.get("why_others_are_weaker", []):
            pdf.cell(6, 4, "•")
            pdf.multi_cell(0, 4, weak)
        pdf.ln(4)

        # Cognitive Biases & Hidden Assumptions
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "Hidden Assumptions & Cognitive Biases", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        for ha in report.get("hidden_assumptions", []):
            pdf.cell(6, 4, "•")
            pdf.multi_cell(0, 4, f"Assumption: {ha}")
        for cb in report.get("cognitive_biases", []):
            pdf.cell(6, 4, "•")
            pdf.multi_cell(0, 4, f"Bias: {cb}")
        pdf.ln(4)

        # Next Steps
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "30-60-90 Day Implementation Plan", new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        for ns in report.get("action_plan_30_60_90", []):
            pdf.cell(6, 4, "-")
            pdf.multi_cell(0, 4, ns)

        return bytes(pdf.output())

    def _sanitize_list(self, items: Any) -> List[str]:
        """Ensures input is converted safely to a non-empty list of clean strings."""
        if isinstance(items, list) and len(items) > 0:
            cleaned = [str(item).strip() for item in items if item and str(item).strip()]
            if cleaned:
                return cleaned
        return ["Evaluated and confirmed."]

    def _sanitize_score(self, score: Any) -> int:
        """Sanitizes confidence score to an integer between 0 and 100."""
        try:
            val = int(score)
            return max(0, min(100, val))
        except (ValueError, TypeError):
            return 85

    def _get_default_report(self, title: str) -> Dict[str, Any]:
        """Provides a safe fallback report structure."""
        return {
            "title": title,
            "executive_summary": "Decision report generated using fallback parameters.",
            "decision_overview": "Overview unavailable.",
            "recommended_option": "Primary Choice",
            "confidence_score": 75,
            "why_recommended_wins": ["Highest overall alignment with primary goal"],
            "why_others_are_weaker": ["Higher execution complexity in alternatives"],
            "hidden_assumptions": ["Assuming current personal/market capacity remains stable"],
            "cognitive_biases": ["Status Quo Bias"],
            "action_plan_30_60_90": ["Days 1-30: Align key stakeholders and monitor initial metrics"],
            "contingency_triggers": ["Re-evaluate if timeline lags by over 30 days"],
            "pros": ["Decisive action prevents opportunity loss."],
            "cons": ["Uncertainty in external variables."],
            "trade_offs": ["Speed of execution vs completeness of information."],
            "risk_assessment": ["Delayed timeline"],
            "opportunities": ["Unlocks strategic clarity"],
            "key_takeaways": ["Take decisive action while managing downside risk."],
            "next_steps": ["Review constraints and align stakeholders."]
        }
